    <h1>Daily Cash Voucher Privacy Policy</h1>
    <p class="updated">Last updated: 13 September 2026</p>

    <p>Daily Cash Voucher is an internal business application for recording daily sales,
    expenses, cash counts, receipts and accounting review information for participating
    organisations and outlets.</p>

    <h2>Information we process</h2>
    <ul>
        <li>Account information such as name, email address, role and assigned outlets.</li>
        <li>Voucher information such as sales, expenses, payment methods, cash counts,
            variance and posting status.</li>
        <li>Receipt images and optional OCR suggestions supplied by the user.</li>
        <li>Technical information required for authentication and synchronisation,
            including a device label and a locally stored session token.</li>
    </ul>

    <h2>How information is used</h2>
    <p>We use this information to authenticate users, enforce role and outlet access,
    save and synchronise vouchers, provide receipt and review workflows, maintain audit
    history, and support the organisation using the service.</p>

    <h2>Sharing</h2>
    <p>Information is shared with authorised users in the same organisation according to
    their role and outlet access. It may also be processed by the organisation's hosting,
    database and file-storage providers to operate the service. We do not sell personal
    information or use it for advertising.</p>

    <h2>Retention and deletion</h2>
    <p>Organisations control business-record retention. Voucher, journal and receipt
    records may be retained for accounting and audit purposes. Users can request account
    or personal-data changes or deletion through their organisation administrator,
    subject to legal and accounting obligations.</p>

    <h2>Security</h2>
    <p>Access is protected with authenticated accounts, role-based permissions and
    protected session tokens. Organisations should deploy the API over HTTPS and protect
    administrator credentials and signing keys.</p>

    <h2>Children</h2>
    <p>This is a business application and is not directed to children under 13.</p>

    <h2>Contact</h2>
    <p>For privacy questions or requests, contact your organisation administrator or
    email <a href="mailto:admin@horixpro.com">admin@horixpro.com</a>.</p>
